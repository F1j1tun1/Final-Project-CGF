#!/usr/bin/env python3
"""Offline analysis of a soundtrack for the on-stage band.

Writes `<soundtrack>.sync` next to each MP3: the beat times (dynamic-programming beat tracker after
D. Ellis, 2007) and four energy curves sampled at 4 Hz (low, mid, high band and percussive attack).
The game reads these files so the musicians play in time with the song that is actually playing.

Needs: ffmpeg on PATH, numpy, scipy.   Usage: analyze_soundtrack.py FILE.mp3 [FILE2.mp3 ...]
"""
import subprocess
import sys
import tempfile
from pathlib import Path

import numpy as np
import scipy.io.wavfile as wavfile
from scipy.signal import stft

SR = 22050
HOP = 441            # 50 analysis frames per second
FPS = SR / HOP
CURVE_RATE = 4       # energy samples per second stored in the file


def load(path):
    with tempfile.TemporaryDirectory() as tmp:
        wav = Path(tmp) / "mono.wav"
        subprocess.run(["ffmpeg", "-v", "error", "-y", "-i", str(path), "-ac", "1", "-ar", str(SR), str(wav)], check=True)
        _, data = wavfile.read(wav)
    return data.astype(np.float64) / 32768.0


def spectrogram(signal):
    freqs, _, z = stft(signal, fs=SR, nperseg=1024, noverlap=1024 - HOP, boundary=None, padded=False)
    return freqs, np.abs(z)


def band(freqs, mag, lo, hi):
    return np.sqrt((mag[(freqs >= lo) & (freqs < hi)] ** 2).mean(axis=0))


def onset_envelope(freqs, mag):
    sel = (freqs >= 30) & (freqs < 8000)
    logmag = np.log1p(100.0 * mag[sel])
    flux = np.maximum(0.0, np.diff(logmag, axis=1, prepend=logmag[:, :1])).sum(axis=0)
    flux -= np.convolve(flux, np.ones(25) / 25, mode="same")   # remove the slow trend
    flux = np.maximum(flux, 0.0)
    return flux / (flux.std() + 1e-9)


def estimate_period(env):
    """Beat period in frames: autocorrelation with a log-normal tempo prior around 115 BPM."""
    n = len(env)
    ac = np.correlate(env, env, mode="full")[n - 1:]
    ac /= ac[0] + 1e-9
    lags = np.arange(len(ac))
    bpm = 60.0 * FPS / np.maximum(lags, 1)
    prior = np.exp(-0.5 * (np.log2(bpm / 115.0) / 0.9) ** 2)
    score = ac * prior
    valid = (bpm >= 60) & (bpm <= 190)
    score[~valid] = 0
    return int(np.argmax(score)), float(score.max())


def track_beats(env, period, tightness=100.0):
    n = len(env)
    score = np.zeros(n)
    back = np.full(n, -1)
    window = np.arange(-int(2 * period), -int(round(period / 2)) + 1)
    penalty = -tightness * (np.log(-window / period) ** 2)
    for t in range(n):
        lo = t + window[0]
        if lo < 0:
            idx = window[window + t >= 0]
            pen = penalty[window + t >= 0]
        else:
            idx, pen = window, penalty
        if len(idx) == 0:
            score[t] = env[t]
            continue
        cand = score[t + idx] + pen
        best = int(np.argmax(cand))
        if cand[best] > 0:
            score[t] = env[t] + cand[best]
            back[t] = t + idx[best]
        else:
            score[t] = env[t]
    # Start the trace at the best local maximum in the last beat period.
    tail = score[-int(period):]
    t = n - int(period) + int(np.argmax(tail))
    beats = [t]
    while back[t] >= 0:
        t = back[t]
        beats.append(t)
    return np.array(beats[::-1]) / FPS


def curve(values, seconds):
    """Mean over 1/CURVE_RATE s windows, scaled so the 95th percentile is 1."""
    step = int(round(FPS / CURVE_RATE))
    count = int(seconds * CURVE_RATE)
    out = np.array([values[i * step:(i + 1) * step].mean() if i * step < len(values) else 0.0 for i in range(count)])
    ref = np.percentile(out, 95) + 1e-9
    return np.clip(out / ref, 0.0, 1.0)


def analyze(path):
    signal = load(path)
    seconds = len(signal) / SR
    freqs, mag = spectrogram(signal)
    env = onset_envelope(freqs, mag)
    period, confidence = estimate_period(env)
    beats = track_beats(env, period)
    intervals = np.diff(beats)
    bpm = 60.0 / np.median(intervals)
    # Bars are assumed to be four beats long; the downbeat is the beat position where low-frequency
    # energy and attacks are strongest on average.
    frames = np.minimum((beats * FPS).astype(int), len(env) - 1)
    weight = band(freqs, mag, 40, 250)
    weight = weight / (weight.std() + 1e-9)
    downbeat = int(np.argmax([(env[frames[k::4]] + weight[frames[k::4]]).mean() for k in range(4)]))
    curves = {
        "low": curve(band(freqs, mag, 40, 250), seconds),
        "mid": curve(band(freqs, mag, 250, 1500), seconds),
        "high": curve(band(freqs, mag, 1500, 6000), seconds),
        "hit": curve(env, seconds),
    }
    out = Path(path).with_suffix(".sync")
    with open(out, "w", encoding="utf-8") as f:
        f.write("# Jester Jack soundtrack sync v1 (generated by scripts/analyze_soundtrack.py)\n")
        f.write(f"duration {seconds:.2f}\n")
        f.write(f"bpm {bpm:.2f}\n")
        f.write(f"downbeat {downbeat}\n")
        f.write("beats " + " ".join(f"{b:.3f}" for b in beats) + "\n")
        f.write(f"rate {CURVE_RATE}\n")
        for name, values in curves.items():
            f.write(name + " " + " ".join(str(int(round(v * 99))) for v in values) + "\n")
    print(f"{Path(path).name}: {seconds:6.1f}s  {bpm:6.1f} BPM  beats={len(beats)}  "
          f"downbeat={downbeat}  interval spread={intervals.std() / intervals.mean() * 100:4.1f}%  period confidence={confidence:.2f}")


if __name__ == "__main__":
    if len(sys.argv) < 2:
        sys.exit(__doc__)
    for name in sys.argv[1:]:
        analyze(name)
